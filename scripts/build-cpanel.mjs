/**
 * Assembles the cPanel deployable: `next build` in standalone mode, then the three folders
 * the runtime expects next to `server.js`.
 *
 * Why a script instead of a checklist: the standalone output is incomplete on its own. Next
 * documents that `public/` and `.next/static/` must be copied into it by hand, and forgetting
 * either one ships a site that renders HTML with no CSS, or with broken logo textures — which
 * is exactly the class of bug that is invisible in a local `next dev`. Doing it here means
 * `npm run deploy:cpanel` is the whole deploy.
 *
 * Output: `deploy/cpanel/`, ready to zip and extract over the application root in cPanel.
 * The `app.cjs` at its root is the file to set as "Application startup file". No
 * `node_modules` ships in it — see `removeNodeModules()` for why that is deliberate.
 */
import { cp, rm, mkdir, stat, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const STANDALONE = path.join(ROOT, '.next', 'standalone');
const STATIC = path.join(ROOT, '.next', 'static');
const PUBLIC = path.join(ROOT, 'public');
const OUT = path.join(ROOT, 'deploy', 'cpanel');

function run(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: ROOT, stdio: 'inherit', shell: process.platform === 'win32' });
    child.on('error', reject);
    child.on('exit', (code) => {
      if (code === 0) resolve();
      else reject(new Error(`${command} ${args.join(' ')} exited with code ${code}`));
    });
  });
}

async function exists(target) {
  try {
    await stat(target);
    return true;
  } catch {
    return false;
  }
}

async function copyInto(source, target, label) {
  if (!(await exists(source))) {
    throw new Error(`Missing ${label}: ${source}. Run "npm run build" first.`);
  }
  await cp(source, target, { recursive: true, force: true });
  console.log(`  copied ${label}`);
}

/**
 * Drops the `node_modules` the standalone trace carries — this host must never receive one.
 *
 * Two independent reasons this folder cannot travel in the zip, not just one:
 *
 * 1. It is built on Windows (as this repo is). `sharp`, a devDependency, ships a native `@img/*`
 *    binary for the machine that built it; shipped to a Linux account, that is a module that
 *    cannot load at all, not just dead weight.
 * 2. CloudLinux's Node.js Selector (the Node host this project actually deploys to) refuses to
 *    start an app that has a real `node_modules` folder in its root at all: it manages
 *    dependencies itself, through a `node_modules` that is a symlink into a separate virtual
 *    environment, and errors immediately — `ERR_REQUIRE_ESM`'s sibling failure mode — if it
 *    finds a plain directory sitting where it expects that symlink.
 *
 * Dependencies are installed once, on the host, through "Run NPM Install" in the Node.js app
 * screen — against the very same `package.json` this script ships — not from anything in this
 * zip. See DEPLOY-CPANEL.md.
 */
async function removeNodeModules() {
  await rm(path.join(OUT, 'node_modules'), { recursive: true, force: true });
  console.log('  removed node_modules (installed on the host instead — see DEPLOY-CPANEL.md)');
}

/**
 * Writes the entry point cPanel actually starts, instead of pointing the app at `server.js`.
 *
 * Two unrelated host quirks, both worked around in this one file:
 *
 * 1. Next's standalone server binds to `process.env.HOSTNAME` when it is set. Shared hosts set
 *    that variable to the machine's own name (`server42.provider.com`), which is not a local
 *    address, so the bind fails with `EADDRNOTAVAIL` and the app dies on boot with a message
 *    that looks like a Next.js bug. Passenger/LiteSpeed ignore the port we pass and hand the
 *    app its own socket, so all that matters is that the host is loopback.
 *
 * 2. LiteSpeed's own Node launcher (`lsnode.js`) loads the startup file with `require()`, never
 *    `import`. The rest of this project is `"type": "module"`, so a plain `app.js` is an ES
 *    module — and `require()` cannot load one at all, failing immediately with
 *    `ERR_REQUIRE_ESM` before a single line of this file runs. The `.cjs` extension opts this
 *    one file out of that, back into CommonJS, where `require()` works — but CommonJS has no
 *    top-level `await`, so the dynamic `import()` of `server.js` has to sit inside an async
 *    IIFE instead of a bare `await` at module scope.
 */
const APP_ENTRY = `// Generated by scripts/build-cpanel.mjs -- do not edit by hand.
// See DEPLOY-CPANEL.md. Passenger/LiteSpeed proxy to this process; it only needs to listen.
// .cjs on purpose: lsnode.js (LiteSpeed's Node launcher) requires its startup file with
// require(), which cannot load an ES module -- and this package is "type": "module".
process.env.HOSTNAME = '127.0.0.1';
(async () => {
  // Dynamic import, not a static one: a static import is hoisted above the HOSTNAME
  // assignment, and server.js reads HOSTNAME at module scope.
  await import('./server.js');
})();
`;

async function writeEntryPoint() {
  await writeFile(path.join(OUT, 'app.cjs'), APP_ENTRY, 'utf8');
  console.log('  wrote app.cjs');
}

async function main() {
  console.log('> building standalone output');
  await run('npm', ['run', 'build']);

  console.log('> assembling deploy/cpanel');
  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });

  // The standalone folder is the application root: server.js and its server chunks live
  // here already, alongside a node_modules this script removes again right below.
  await copyInto(STANDALONE, OUT, '.next/standalone');
  // Static assets are NOT part of the trace (they are never imported by the server bundle).
  await copyInto(STATIC, path.join(OUT, '.next', 'static'), '.next/static');
  // Same for anything served from the public root: logos, covers, fonts, certificates.
  await copyInto(PUBLIC, path.join(OUT, 'public'), 'public');
  await removeNodeModules();
  await writeEntryPoint();

  console.log(`
Done. Application root to upload: deploy/cpanel
  - Application startup file: app.cjs
  - Required environment variables: see DEPLOY-CPANEL.md
`);
}

main().catch((error) => {
  console.error(`\nBuild failed: ${error.message}`);
  process.exitCode = 1;
});
